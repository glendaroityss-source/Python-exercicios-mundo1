a = input('Digite algo:')
print('O tipo primitivo é', type(a))
print('É algo numerico?',a.isnumeric())
print('É algo alfabético sem espaços e sem acentuacao?',a.isalpha())
print('É algo que tem letras e/ou números sem espacos?',a.isalnum())
print('É algo que tem letras maiusculas e/ou minusculas?',a.isspace())
print('É algo que so tem letras minúsculas?',a.islower())
print('É algo que só tem letras MAIÚSCULAS',a.isupper())
print('É algo que tem somente espaços?',a.isspace())



