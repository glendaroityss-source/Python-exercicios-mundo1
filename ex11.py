largura = float(input('Qual é a largura da parede?'))
altura = float(input('Qual é a altura da parede?'))
dimensao = (f'{largura}x{altura}')
area = largura*altura
quantidade = area/2
print(f'Sua dimensão é {dimensao}, sua área é {area} e a quatidade de tinta em litros que você usará é {quantidade}litros')

